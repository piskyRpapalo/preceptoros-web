import assert from 'node:assert/strict';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const B = require('../public/game/bubble_language.js');
const W = require('../public/assets/worm_transition.js');
const a = [20, 100], b = [20, 300];
const start = B.neck(a, b, 48, 0);
const middle = B.neck(a, b, 48, 0.5);
const end = B.neck(a, b, 48, 1);
assert.deepEqual(start[0], a);
assert.deepEqual(start.at(-1), b);
assert.deepEqual(end, start);
assert.deepEqual(B.neck(a, b, 48, 0.5), middle);
assert.ok(Math.abs(middle[12][0] - 20) > 1, 'the neck must be visible at p=0.5');
assert.throws(() => B.neck(a, b, -1, 0.5), /bubble: neck/);
assert.throws(() => B.neck(a, b, 48, 1.1), /bubble: neck/);
assert.throws(() => B.neck([NaN, 0], b, 48, 0.5), /bubble: neck/);
const worm = W.gusano({ ciclo: 40, delta: 300, intentos: 3, sello: 'LIVE' }, a, b, 0.5);
assert.deepEqual(worm.puntos[0], a);
assert.deepEqual(worm.puntos.at(-1), b);
assert.ok(Math.abs(worm.puntos[12][0] - 20) > 1);
const frame = { v: 'preceptoros.bubble/1', id: 'NECK', atoms: [{ k: 'bridge', i: [{ o: 'neck', a, b, k: 48, p: 0.5, f: 'cyan', s: 'ink', d: 1 }] }] };
const output = B.compile(frame);
assert.equal(B.compile.notes.length, 0);
assert.equal(output.length, 1);
assert.equal(output[0].o, 'neck');
assert.ok(Buffer.byteLength(JSON.stringify(frame)) < 1024);
const invalid = { ...frame, atoms: [{ k: 'bridge', i: [{ o: 'neck', a, b, k: -1, p: 0.5 }] }] };
assert.equal(B.compile(invalid).length, 0);
assert.match(B.compile.notes[0].cause, /NO_DATA/);
console.log(JSON.stringify({ ok: true, points: middle.length, midpoint: middle[12], channel_bytes: Buffer.byteLength(JSON.stringify(frame)) }));
